"""Current patch EUW ranked-matchup baseline from authorised Riot Match-V5.

Rank-bucket weights reflect the user's actual Gold-level Flex group, not a D2+
only view. Each row is labelled by sampled account's rank (not the exact rank
of every lobby participant). Source file is generated by
tools/collect_riot_ranked_matchups.py after the owner supplies a valid API key.
Never invent current samples if the cache is absent or old.
"""
from __future__ import annotations
import json
import os
import sys
from functools import lru_cache
from pathlib import Path

from league_source_stats import source_mtime_ns

TIER_WEIGHTS = {"GOLD": 0.40, "PLATINUM": 0.25, "EMERALD": 0.25, "DIAMOND": 0.10}
MIN_GAMES = 30
MIN_BASELINE = 75


def _folder() -> Path:
    override = os.getenv("DRAFTCOACH_RIOT_SAMPLE_DIR", "").strip()
    base = Path(sys.executable).resolve().parent if getattr(sys, "frozen", False) else Path(__file__).resolve().parent
    return Path(override) if override else base / "var" / "riot-rank-samples"


@lru_cache(maxsize=3)
def _load(path: str, stamp: int) -> dict:
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except (ValueError, OSError):
        return {}
    if (data.get("schema_version") != 1 or data.get("provider") != "Riot Match-V5"
        or data.get("region") != "EUW" or data.get("queue") != 420):
        return {}
    return data


def _patch(value: str) -> str:
    parts = str(value).split(".")
    if len(parts) >= 2 and parts[0] == "26":
        return "16." + parts[1]
    return ".".join(parts[:2])


def ranked_matchup(role: str, ours: str, enemy: str, *, patch: str = "26.21") -> dict:
    source = _folder() / "ranked-matchups.json"
    if not source.is_file():
        return {}
    data = _load(str(source), source_mtime_ns(source))
    lookup_patch = _patch(patch)
    weighted = 0.0
    weight_sum = 0.0
    used = []
    for tier, intended_weight in TIER_WEIGHTS.items():
        key = "|".join((tier, lookup_patch, role, ours, enemy))
        row = (data.get("matchups") or {}).get(key)
        if not row:
            continue
        n, baseline = int(row.get("games") or 0), int(row.get("overall_games") or 0)
        if n < MIN_GAMES or baseline < MIN_BASELINE:
            continue
        residual = max(-8.0, min(8.0, float(row.get("residual_pp") or 0)))
        confidence = n / (n + 150.0)
        weighted += intended_weight * confidence * residual
        weight_sum += intended_weight
        used.append({
            "tier": tier, "games": n, "baseline_games": baseline,
            "residual_pp": residual, "confidence": round(confidence, 3),
        })
    if not used or weight_sum <= 0:
        return {}
    residual_weighted = weighted / weight_sum
    points = round(max(-2.4, min(2.4, residual_weighted * 0.46)), 3)
    return {
        "source": "Riot Match-V5 private EUW ranked sample",
        "url": "https://developer.riotgames.com/apis#match-v5",
        "patch": lookup_patch, "tier_semantics": "rank-anchored sample, not exact lobby tier",
        "tiers": used, "games": sum(entry["games"] for entry in used),
        "adjusted_matchup_pp": round(residual_weighted, 2),
        "draft_points": points,
        "evidence_kind": "current_patch_soloqueue_anchor_sample",
    }


def sample_status() -> dict:
    src = _folder() / "ranked-matchups.json"
    if not src.is_file():
        return {"installed": False, "reason": "Riot API key and collection not configured"}
    data = _load(str(src), source_mtime_ns(src))
    return {"installed": bool(data), "sampled_matches": data.get("sampled_matches", {}),
            "matchup_rows": data.get("matchup_rows", 0),
            "tier_weights": TIER_WEIGHTS,
            "source": "Riot Match-V5", "queue": 420}
